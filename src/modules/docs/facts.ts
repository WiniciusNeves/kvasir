import fs from 'fs';
import path from 'path';
import { lastCommitTouching, getCommitsSince, getChangedFilesSince, getFileDiffSince, getFileAtRef, refExists } from '@utils/git';
import type { ChangedFile } from '@utils/git';
import { listExports } from '@utils/imports';
import { truncateForPrompt } from '@ai/parse';
import { projectDocsDir } from '@modules/doc/folder';
import { parseSections, splitLines } from './sections';
import type { Section } from './sections';

// What changed in the code since the docs were last touched, computed by code. The model only writes
// the text; it never decides what changed.

export interface CodeChange extends ChangedFile {
  exports: string[];
  // exported before (at the base) and gone now: renamed or removed
  removedExports: string[];
  // exported now and not at the base (every export of a new file)
  addedExports: string[];
  diff: string;
}

export interface DocCandidate {
  file: string;
  content: string;
  sections: Section[];
  // sections that mention something that changed (a file, an export, a script)
  mentioned: Section[];
  // names this doc cites that do not exist anymore (exports, files, scripts)
  stale: string[];
  // new exports and scripts this doc never mentions
  undocumented: string[];
}

export interface DocsFacts {
  base: string;
  baseIsDocsCommit: boolean;
  commits: string[];
  changes: CodeChange[];
  scripts: Record<string, string>;
  addedScripts: string[];
  removedScripts: string[];
  terms: string[];
  docs: DocCandidate[];
}

const DOC_EXTENSIONS = /\.(md|mdx)$/i;
// generated by kvasir doc / release: regenerated by their own commands
const GENERATED_DOCS = /(^|\/)(code|libs)\/|CHANGELOG\.md$/i;
const CODE_FILE = /\.(ts|tsx|js|jsx|mjs|cjs|py|go|rs|java|kt|swift|dart|vue|svelte|json)$/i;
const NOT_CODE = /(^|\/)(node_modules|dist|build|\.kvasir)\/|package-lock\.json$|\.d\.ts$/;
const MAX_DOCS = 20;
const MAX_DIFF_PER_FILE = 1200;
const MIN_TERM = 4;

function readJsonFile<T>(file: string): T | null {
  try {
    return JSON.parse(fs.readFileSync(file, 'utf-8')) as T;
  } catch {
    return null;
  }
}

function listDocFiles(root: string): string[] {
  const docs: string[] = [];
  const readme = fs.readdirSync(root).find((name) => /^readme\.md$/i.test(name));
  if (readme) docs.push(readme);

  const dir = projectDocsDir(root);
  const walk = (current: string): void => {
    if (!fs.existsSync(current)) return;
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      const relative = path.relative(root, full).split(path.sep).join('/');
      if (entry.isDirectory()) walk(full);
      else if (DOC_EXTENSIONS.test(entry.name) && !GENERATED_DOCS.test(relative)) docs.push(relative);
    }
  };
  walk(path.join(root, dir));
  return docs.slice(0, MAX_DOCS);
}

function escapeRegex(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// An identifier only code would use (camelCase, PascalCase, UPPER_SNAKE): "agents" appears in any
// text, "agentForTask" only where the doc talks about that function.
const CODE_LIKE = /[a-z][A-Z]|^[A-Z][a-z]+[A-Z]|^[A-Z0-9]+_[A-Z0-9_]+$|_/;

// "styles.ts" or "index.ts" in a doc says nothing about which file it means.
function isSpecificName(name: string): boolean {
  return name.length >= MIN_TERM && !/^(index|types|utils|main|styles)\.\w+$/i.test(name);
}

// Names whose presence in a doc means the doc talks about what changed: paths, file names with
// extension, code-like export names, and scripts as "npm run x".
function termsFor(changes: CodeChange[], scripts: string[]): string[] {
  const names = new Set<string>();
  for (const change of changes) {
    for (const file of [change.path, change.from].filter((item): item is string => Boolean(item))) {
      names.add(file);
      names.add(path.basename(file));
    }
    [...change.exports, ...change.removedExports].filter((name) => CODE_LIKE.test(name)).forEach((name) => names.add(name));
  }
  scripts.forEach((name) => names.add(`npm run ${name}`));
  return [...names].filter(isSpecificName);
}

export function collectDocsFacts(root: string, since?: string): DocsFacts | null {
  const docFiles = listDocFiles(root);
  if (docFiles.length === 0) return null;

  const docsDir = projectDocsDir(root);
  const lastDocsCommit = lastCommitTouching(docFiles.length > 0 ? [...docFiles, docsDir] : ['README.md']);
  const base = since ?? lastDocsCommit;
  if (!base || !refExists(base)) return null;

  const changes: CodeChange[] = getChangedFilesSince(base)
    .filter((change) => CODE_FILE.test(change.path) && !NOT_CODE.test(change.path) && !DOC_EXTENSIONS.test(change.path))
    .map((change) => {
      const absolute = path.join(root, change.path);
      const content = change.status !== 'deleted' && fs.existsSync(absolute) ? fs.readFileSync(absolute, 'utf-8') : '';
      const diff = change.status === 'added' ? truncateForPrompt(content, MAX_DIFF_PER_FILE) : truncateForPrompt(getFileDiffSince(base, change.path), MAX_DIFF_PER_FILE);
      const exports = content ? listExports(content) : [];
      const before = change.status === 'added' ? null : getFileAtRef(base, change.from ?? change.path);
      const exportsBefore = before ? listExports(before) : [];
      const removedExports = exportsBefore.filter((name) => !exports.includes(name));
      const addedExports = exports.filter((name) => !exportsBefore.includes(name));
      return { ...change, exports, removedExports, addedExports, diff };
    });

  const scripts = readJsonFile<{ scripts?: Record<string, string> }>(path.join(root, 'package.json'))?.scripts ?? {};
  const scriptsBefore = Object.keys((JSON.parse(getFileAtRef(base, 'package.json') ?? '{}') as { scripts?: Record<string, string> }).scripts ?? {});
  const addedScripts = Object.keys(scripts).filter((name) => !scriptsBefore.includes(name));
  const removedScripts = scriptsBefore.filter((name) => !(name in scripts));
  const scriptsChanged = changes.some((change) => change.path === 'package.json');
  const terms = termsFor(changes, scriptsChanged ? [...Object.keys(scripts), ...removedScripts] : []);
  const patterns = terms.map((term) => new RegExp(`(^|[^\\w])${escapeRegex(term)}([^\\w]|$)`));

  const docs: DocCandidate[] = docFiles.map((file) => {
    const content = fs.readFileSync(path.join(root, file), 'utf-8');
    const { lines } = splitLines(content);
    const sections = parseSections(lines);
    const mentioned = sections.filter((section) => {
      const text = lines.slice(section.start, section.end).join('\n');
      return patterns.some((pattern) => pattern.test(text));
    });
    const cites = (name: string): boolean => new RegExp(`(^|[^\\w])${escapeRegex(name)}([^\\w]|$)`).test(content);
    const gone = [
      ...changes.flatMap((change) => change.removedExports),
      ...changes.filter((change) => change.status === 'deleted' || change.status === 'renamed').map((change) => change.from ?? change.path),
      ...removedScripts.map((name) => `npm run ${name}`),
    ];
    // A new export is only "missing" from a doc that already talks about its file (the path, the file
    // name or another export of it): a decision log that cites one component is not where 400 new
    // styled components of other files go. New scripts belong where the doc lists scripts.
    const talksAbout = (change: CodeChange): boolean =>
      [change.path, change.from ?? '', path.basename(change.path)].filter(isSpecificName).some(cites) ||
      change.exports.filter((name) => CODE_LIKE.test(name) && !change.addedExports.includes(name)).some(cites);
    const fresh = [
      ...changes.filter((change) => change.status !== 'deleted' && talksAbout(change)).flatMap((change) => change.addedExports),
      ...(/npm run /.test(content) ? addedScripts.map((name) => `npm run ${name}`) : []),
    ];
    const stale = [...new Set(gone.filter(cites))];
    const undocumented = [...new Set(fresh.filter((name) => !cites(name)))];
    return { file, content, sections, mentioned, stale, undocumented };
  });

  return {
    base,
    baseIsDocsCommit: !since,
    commits: getCommitsSince(base),
    changes,
    scripts,
    addedScripts,
    removedScripts,
    terms,
    // the README is where new things are announced: always a candidate when code changed
    docs: docs.filter((doc) => doc.mentioned.length > 0 || (/^readme\.md$/i.test(doc.file) && changes.length > 0)),
  };
}
