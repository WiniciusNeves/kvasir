import os from 'os';
import path from 'path';
import fs from 'fs-extra';
import { readContext } from '@modules/init/contextWriter';
import { writeFile, readFile, readJson } from '@utils/fs';
import { loadPersona } from '@modules/init/personaLoader';
import type { KvasirContext } from '@ktypes/context';
import type { Persona } from '@ktypes/persona';

interface PackageJson {
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
  scripts?: Record<string, string>;
}

interface TsconfigJson {
  compilerOptions?: {
    paths?: Record<string, string[]>;
  };
}

interface TemplateInfo {
  label: string;
  // absolute path of the template file
  path: string;
}

const IGNORED_ENTRIES = new Set(['node_modules', '.git', 'dist', 'build', '.next', '.turbo', 'coverage']);
const MAX_TREE_DEPTH = 2;
const HEADER_START = '<!-- kvasir:header:start -->';
const HEADER_END = '<!-- kvasir:header:end -->';

// Company CLAUDE.md templates are personal (they describe a company's architecture), so they are
// never shipped with Kvasir: ~/.kvasir/templates/<persona>-mobile.md or <persona>-web.md.
function getTemplatesDir(): string {
  return path.join(os.homedir(), '.kvasir', 'templates');
}

function resolveTemplate(pkg: PackageJson, personaName: string): TemplateInfo | null {
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const kind = deps.expo || deps['react-native'] ? 'mobile' : deps.next ? 'web' : null;
  if (!kind || !personaName) return null;

  const file = path.join(getTemplatesDir(), `${personaName}-${kind}.md`);
  return fs.pathExistsSync(file) ? { label: `${personaName} ${kind}`, path: file } : null;
}

async function buildDirectoryTree(dir: string, depth: number = 0, prefix: string = ''): Promise<string[]> {
  if (depth > MAX_TREE_DEPTH) return [];

  const exists = await fs.pathExists(dir);
  if (!exists) return [];

  const entries = await fs.readdir(dir, { withFileTypes: true });
  const visible = entries
    .filter((entry) => !IGNORED_ENTRIES.has(entry.name) && !entry.name.startsWith('.'))
    .sort((a, b) => {
      if (a.isDirectory() !== b.isDirectory()) return a.isDirectory() ? -1 : 1;
      return a.name.localeCompare(b.name);
    });

  const lines: string[] = [];

  for (const entry of visible) {
    const label = entry.isDirectory() ? `${entry.name}/` : entry.name;
    lines.push(`${prefix}${label}`);

    if (entry.isDirectory()) {
      const childLines = await buildDirectoryTree(path.join(dir, entry.name), depth + 1, `${prefix}  `);
      lines.push(...childLines);
    }
  }

  return lines;
}

function formatDependencies(deps: Record<string, string> | undefined): string[] {
  if (!deps) return [];
  return Object.entries(deps)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, version]) => `- ${name}: ${version}`);
}

function formatPersonaSection(persona: Persona): string[] {
  return [
    `## Persona: ${persona.name}`,
    '',
    `Stack: ${persona.stack.join(', ')}`,
    '',
    '### Repository naming',
    `- Pattern: ${persona.repoNaming.pattern}`,
    `- Suffixes: ${persona.repoNaming.suffixes.join(' · ')}`,
    '',
    '### Branch naming (Git Flow)',
    ...persona.branchRules.map((rule) => `- \`${rule.prefix}\` — ${rule.description}`),
    '',
    '### Commit convention',
    `- ${persona.commitRules.convention}: \`${persona.commitRules.format}\` (${persona.commitRules.language})`,
    `- Types: ${persona.commitRules.types.join(', ')}`,
    '',
    `Language rule: all branch names, commit messages, and repository names must be in ${persona.language}.`,
    '',
  ];
}

function buildHeader(
  ctx: KvasirContext,
  pkg: PackageJson,
  paths: Record<string, string[]> | undefined,
  template: TemplateInfo | null
): string {
  const lines: string[] = [];

  lines.push(HEADER_START);
  lines.push(`# CLAUDE.md — ${ctx.project.name}`, '');
  lines.push(`- Persona: ${ctx.project.persona}`);
  if (template) {
    lines.push(`- Template: ${template.label} — ~/.kvasir/templates/${path.basename(template.path)}`);
  }
  lines.push(`- Stack: ${ctx.project.stack.join(', ') || 'unknown'}`, '');

  const dependencies = formatDependencies(pkg.dependencies);
  if (dependencies.length > 0) {
    lines.push('### Detected dependencies', ...dependencies, '');
  }

  const devDependencies = formatDependencies(pkg.devDependencies);
  if (devDependencies.length > 0) {
    lines.push('### Detected dev dependencies', ...devDependencies, '');
  }

  if (paths && Object.keys(paths).length > 0) {
    lines.push('### Path aliases');
    for (const [alias, targets] of Object.entries(paths)) {
      lines.push(`- \`${alias}\` → \`${targets.join(', ')}\``);
    }
    lines.push('');
  }

  lines.push('### Active task');
  lines.push(ctx.activeTask ? `- ${ctx.activeTask.id} — ${ctx.activeTask.title}` : '- None', '');

  lines.push(
    '> Auto-generated by `kvasir init`. Only this header block is refreshed on future runs — everything below it is preserved.',
    ''
  );
  lines.push(HEADER_END);

  return lines.join('\n');
}

async function buildFallbackBody(ctx: KvasirContext, pkg: PackageJson, persona: Persona | null): Promise<string> {
  const lines: string[] = [];

  const scripts = pkg.scripts ?? {};
  if (Object.keys(scripts).length > 0) {
    lines.push('## Available scripts');
    for (const [name, command] of Object.entries(scripts)) {
      lines.push(`- \`npm run ${name}\` — ${command}`);
    }
    lines.push('');
  }

  const directoryTree = await buildDirectoryTree(process.cwd());
  if (directoryTree.length > 0) {
    lines.push('## Folder structure', '```', ...directoryTree, '```', '');
  }

  lines.push('## Branch rules');
  lines.push(`- Pattern: ${ctx.branchRules.pattern}`);
  lines.push(`- Prefixes: ${ctx.branchRules.prefix}`);
  lines.push(`- Language: ${ctx.branchRules.language}`, '');

  lines.push('## Commit rules');
  lines.push(`- Convention: ${ctx.commitRules.convention}`);
  lines.push(`- Language: ${ctx.commitRules.language}`);
  lines.push(`- Format: ${ctx.commitRules.format}`, '');

  if (persona) {
    lines.push(...formatPersonaSection(persona));
  }

  lines.push('## Active modules');
  lines.push(`- ${ctx.activeModules.join(', ')}`, '');

  return lines.join('\n');
}

function extractPreservedBody(existingContent: string | null): string | null {
  if (!existingContent) return null;

  const endIndex = existingContent.indexOf(HEADER_END);
  if (endIndex === -1) {
    return existingContent.replace(/^\s+/, '');
  }

  return existingContent.slice(endIndex + HEADER_END.length).replace(/^\s+/, '');
}

// The project's persona, loaded like everywhere else (never a hardcoded one).
async function loadProjectPersona(ctx: KvasirContext): Promise<Persona | null> {
  if (!ctx.project.persona) return null;
  try {
    return await loadPersona(ctx.project.persona);
  } catch {
    return null;
  }
}

export async function writeClaude(): Promise<void> {
  const ctx = await readContext();
  const pkg = (await readJson<PackageJson>('package.json')) ?? {};
  const tsconfig = await readJson<TsconfigJson>('tsconfig.json');
  const paths = tsconfig?.compilerOptions?.paths;

  const template = resolveTemplate(pkg, ctx.project.persona);
  const header = buildHeader(ctx, pkg, paths, template);

  const existingContent = await readFile('CLAUDE.md');
  let body = extractPreservedBody(existingContent);

  if (body === null) {
    body = template ? ((await readFile(template.path)) ?? '') : await buildFallbackBody(ctx, pkg, await loadProjectPersona(ctx));
  }

  const content = `${header}\n\n${body}`.trimEnd() + '\n';
  await writeFile('CLAUDE.md', content);
}
